/**
 * Ограничение частоты повторной отправки письма подтверждения адреса.
 *
 * ЗАЧЕМ СВОЁ ОГРАНИЧЕНИЕ, ЕСЛИ У SUPABASE ТОЖЕ ЕСТЬ ЛИМИТ.
 * На этой версии GoTrue повторные отправки не ограничивает: пять запросов
 * подряд проходят без всякой ошибки (проверено на боевой базе, 04.10.2026).
 * Без ограничения форма «отправить письмо ещё раз» становится чужим
 * инструментом: любой посетитель смог бы слать письма на произвольные
 * адреса от имени GameLand, и Яндекс заблокировал бы наш ящик — а вместе
 * с ним всю отправку с сайта, включая подтверждение адресов реальных
 * покупателей.
 *
 * ПОЧЕМУ ТРИ МИНУТЫ.
 * Ровно столько нужно человеку, который не нашёл письмо: открыть «Спам»,
 * подождать, пока прогрузится почта, и повторить. Меньше — не успеет,
 * больше — он сдастся и уйдёт писать в поддержку. 3 минуты ограничивают
 * один адрес 20 отправками в час, что для настоящего человека незаметно,
 * а для почтового спама — недостаточно.
 *
 * ПОЧЕМУ СЧЁТЧИК В ПАМЯТИ, А НЕ В БАЗЕ.
 * Схему базы из приложения изменить нельзя (нет доступа к Postgres), а
 * таблица ради одного счётчика — лишняя сущность. Из этого следуют два
 * известных ограничения, и их нужно знать:
 *   - перезапуск контейнера обнуляет счётчик;
 *   - при нескольких репликах приложения ограничение считается в каждой
 *     отдельно (сейчас реплика одна).
 * Если реплик станет несколько — перенести в таблицу и считать в SQL.
 */

/** Длина паузы между отправками одного адреса: 3 минуты. */
export const RESEND_COOLDOWN_SECONDS = 180;

const COOLDOWN_MS = RESEND_COOLDOWN_SECONDS * 1000;

/**
 * Больше этого числа адресов в памяти не держим. Реально столько не
 * накопится, но если кто-то начнёт подставлять случайные адреса, память
 * не должна расти бесконечно.
 */
const MAX_TRACKED_EMAILS = 5000;

/** Адрес (в нижнем регистре) → когда последний раз отправляли письмо. */
const lastSentAt = new Map<string, number>();

export type ResendDecision =
  | { allowed: true }
  | { allowed: false; retryAfterSeconds: number };

/**
 * Регистрирует попытку отправки и отвечает, можно ли её выполнить.
 *
 * Сделано одной проверкой и одной записью, без «прочитал — потом записал»:
 * иначе два одновременных запроса с разных вкладок могли бы пройти вместе.
 * Параметр now передаётся только для тестов.
 */
export function reserveConfirmationResend(
  email: string,
  now: number = Date.now(),
): ResendDecision {
  const key = email.trim().toLowerCase();
  const previous = lastSentAt.get(key);

  if (previous !== undefined && now - previous < COOLDOWN_MS) {
    return {
      allowed: false,
      retryAfterSeconds: Math.ceil((COOLDOWN_MS - (now - previous)) / 1000),
    };
  }

  lastSentAt.set(key, now);

  // Подчистка истёкших записей — только когда их накопилось много,
  // чтобы не перебирать карту на каждый клик.
  if (lastSentAt.size > MAX_TRACKED_EMAILS) {
    for (const [tracked, sentAt] of lastSentAt) {
      if (now - sentAt >= COOLDOWN_MS) lastSentAt.delete(tracked);
    }
  }

  return { allowed: true };
}

/** Сбрасывает счётчики. Только для тестов. */
export function resetConfirmationResendLimits(): void {
  lastSentAt.clear();
}