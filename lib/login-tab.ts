/**
 * Правило выбора вкладки на странице входа.
 *
 * Живёт отдельным файлом, а не внутри login-form.tsx, по двум причинам:
 *   - файл с JSX нельзя запустить в обычном Node без сборки, а это
 *     правило стоит проверять тестом (оно определяет, какую форму видит
 *     покупатель, и ошибка в нём тихо ломает путь к покупке);
 *   - правило нужно и серверному компоненту страницы, и клиентскому
 *     компоненту формы — оба без проблем импортируют обычный .ts.
 *
 * ПОЧЕМУ ИМЕННО ТАК. Страница /login попадает в браузер двумя путями, и
 * различие принципиально:
 *
 *   1. Человек уже покупал, и его выбросило с /download — requireUser()
 *      перенаправляет на `/login?next=%2Fdownload`. Такой человек хочет
 *      ВОЙТИ. Показать ему регистрацию значит заставить лишний клик и
 *      показать неверную подпись «Регистрация».
 *   2. Человек пришёл за покупкой впервые. Ему нужна РЕГИСТРАЦИЯ, а вход
 *      бессмысленен: пароля, который он вводит, у него ещё нет.
 *
 * Различить эти случаи можно по параметру next: его присылает requireUser,
 * а по прямой ссылке с лендинга его не будет. Поэтому next означает
 * «вернулись за покупками» → вход, отсутствие next → регистрация.
 *
 * Раньше по умолчанию всегда открывался вход, из-за чего новый покупатель
 * видел форму, которой не мог воспользоваться: ввести пароль, которого у
 * него нет, и получить «Неверный email или пароль».
 */
export type LoginTab = "login" | "signup";

export function defaultTab(hasNextPath: boolean): LoginTab {
  return hasNextPath ? "login" : "signup";
}

/**
 * Разбирает явный выбор вкладки из адреса (?tab=signup).
 *
 * Серверные действия ставят этот параметр, чтобы после ошибки регистрации
 * открылась регистрация, а после сообщения «аккаунт создан, подтвердите
 * почту» — вход. Это важнее правила по next: сообщение об ошибке,
 * показанное на чужой вкладке, выглядит так, будто форма забыла, что
 * человек делал.
 *
 * Мусорное значение игнорируем, чтобы не открыть вкладку, которой нет.
 */
export function resolveTab(
  tab: string | null | undefined,
  hasNextPath: boolean,
): LoginTab {
  if (tab === "login" || tab === "signup") return tab;
  return defaultTab(hasNextPath);
}