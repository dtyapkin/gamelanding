/**
 * Какую вкладку открыть на странице /login.
 *
 * Живёт отдельным файлом, а не внутри login-form.tsx, по двум причинам:
 *   - файл с JSX нельзя запустить в обычном Node без сборки, а это
 *     правило стоит проверять тестом (оно определяет, какую форму видит
 *     покупатель, и ошибка в нём тихо ломает путь к покупке);
 *   - правило нужно и серверному слою (lib/dal.ts строит ссылку на
 *     /login), и клиентскому компоненту формы — оба без проблем
 *     импортируют обычный .ts.
 *
 * ПРАВИЛО ПО УМОЛЧАНИЮ — РЕГИСТРАЦИЯ.
 * Новый покупатель идёт по главной, жмёт «Купить» и попадает на /login.
 * Аккаунта у него ещё нет, пароля тоже. Если открыть вход, он введёт
 * несуществующий пароль и получит «Неверный email или пароль» — путь к
 * покупке сломан. Поэтому форма по умолчанию всегда показывает
 * регистрацию, а на вход человек переключается одним кликом.
 *
 * КОГДА НУЖЕН ВХОД, РЕШАЕТ НЕ АДРЕС, А ТОТ, КТО СОЗДАЛ ССЫЛКУ.
 * Параметр next для этого не годится: и новый покупатель с кнопки
 * «Купить», и вернувшийся покупатель со сломавшейся сессией получают
 * /login?next=/download. Различить их можно только в момент редиректа:
 *   - requireUser("/download", "signup")  — из checkout, новый покупатель;
 *   - requireUser("/download", "login")   — из охраны /download, вернувшийся.
 * Поэтому вкладка передаётся явным параметром tab, а next остаётся только
 * адресом возврата после успешного входа.
 */
export type LoginTab = "login" | "signup";

/**
 * Вкладка по умолчанию, если в адресе нет явного tab.
 *
 * Всегда регистрация: страницу /login впервые открывает новый покупатель.
 */
export function defaultTab(): LoginTab {
  return "signup";
}

/**
 * Разбирает явный выбор вкладки из адреса (?tab=login).
 *
 * Серверные действия и requireUser ставят этот параметр, когда знают, кто
 * пришёл: после ошибки регистрации нужна регистрация, из охраны /download —
 * вход, с кнопки «Купить» — регистрация. Это знание у вызывающего кода есть,
 * у самой страницы его нет, поэтому флаг и передаётся явно.
 *
 * Мусорное значение игнорируем, чтобы не открыть вкладку, которой нет.
 */
export function resolveTab(tab: string | null | undefined): LoginTab {
  if (tab === "login" || tab === "signup") return tab;
  return defaultTab();
}